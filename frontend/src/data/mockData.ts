function pipelineFor(kind: "blocked" | "redacted" | "allowed") {
  if (kind === "allowed") return pipelineAllowed;
  if (kind === "redacted")
    return pipelineAllowed.map((s) =>
      s.name === "Sensitive Data Scan"
        ? { name: s.name, state: "warning" as const, detail: "Sensitive entities redacted" }
        : s.name === "Policy Engine"
          ? { name: s.name, state: "warning" as const, detail: "Redaction policy applied" }
          : s,
    );
  return [
    ...pipelineAllowed.slice(0, 4).map((s) => ({ ...s })),
    {
      name: "Prompt Injection Scan",
      state: "blocked" as const,
      detail: "Injection signature matched",
    },
    { name: "Policy Engine", state: "blocked" as const, detail: "PL-003 Block Prompt Injection" },
    { name: "LLM Request", state: "waiting" as const, detail: "Never forwarded" },
    { name: "Response Scan", state: "waiting" as const, detail: "Skipped" },
    { name: "Audit Log", state: "passed" as const, detail: "Persisted" },
  ];
}

